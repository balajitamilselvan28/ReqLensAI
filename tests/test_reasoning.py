def test_evaluate_candidates_batch():
    req1 = Requirement(requirement_id="R1", original_text="test 1", action="test", actor="a", source_page=1)
    req2 = Requirement(requirement_id="R2", original_text="test 2", action="test", actor="b", source_page=1)
    
    candidate_pair = CandidatePair(requirement_id_1="R1", requirement_id_2="R2", similarity_score=0.9, requirement_text_1="test 1", requirement_text_2="test 2")
    
    agent = LogicalReasoningAgent()
    results = agent.evaluate_candidates([req1, req2], [candidate_pair])
    
    assert len(results) == 1
    assert results[0].has_different_actors is True

def test_integration_knowledge_and_reasoning():
    # 1. Version 2 objects
    req1 = Requirement(
        requirement_id="SYS-01",
        original_text="The system shall wait 10 seconds.",
        actor="The system",
        action="wait",
        numerical_values=[NumericalValue(value=10, unit="seconds")],
        source_page=1
    )
    req2 = Requirement(
        requirement_id="SYS-02",
        original_text="The system shall wait 20 seconds.",
        actor="The system",
        action="wait",
        numerical_values=[NumericalValue(value=20, unit="seconds")],
        source_page=1
    )
    
    # 2. Knowledge Representation
    kg_agent = KnowledgeRepresentationAgent()
    representations = kg_agent.transform([req1, req2])
    
    assert len(representations) == 2
    assert any(e.label == "NumericalValue" and e.name == "10.0 seconds" for e in representations[0].entities)
    
    # 3. Logical Reasoning
    # Note: We simulate Candidate Pair being generated by V3
    pair = CandidatePair(requirement_id_1="SYS-01", requirement_id_2="SYS-02", similarity_score=0.95, requirement_text_1="", requirement_text_2="")
    
    reasoning_agent = LogicalReasoningAgent()
    results = reasoning_agent.evaluate_candidates([req1, req2], [pair])
    
    assert len(results) == 1
    reasoning = results[0]
    
    assert reasoning.has_overlapping_actions is True
    assert reasoning.has_different_actors is False
    assert reasoning.has_numerical_overlap is True
    assert "10.0 vs 20.0" in reasoning.numerical_comparison

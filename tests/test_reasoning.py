import pytest
from src.schemas.data_models import Requirement, CandidatePair, NumericalValue
from src.agents.reasoning import LogicalReasoningAgent
from src.agents.representation import KnowledgeRepresentationAgent

def test_permission_rule_representation():
    req1 = Requirement(requirement_id="REQ-001", original_text="Students shall be allowed to register for events.", actor="Students", action="register", object="events", source_page=1)
    req2 = Requirement(requirement_id="REQ-002", original_text="Only administrators shall be allowed to register students.", actor="administrators", action="register", object="students", source_page=1)
    
    agent = LogicalReasoningAgent()
    result = agent.evaluate_pair(req1, req2)
    
    # Actions overlap, but actors are different.
    assert result.has_overlapping_actions is True
    assert result.has_different_actors is True
    assert "Different actors" in result.reasoning_details

def test_numerical_constraint_comparison():
    req1 = Requirement(requirement_id="REQ-003", original_text="respond in 300 ms", action="respond", numerical_values=[NumericalValue(value=300, unit="ms")], source_page=1)
